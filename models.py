class SearchVaultEntry(BaseModel):
    """
    A saved search configuration with metadata for the Search Vault.

    Generated by: main.py (on user save)
    Persisted by: database.py (search_vault table)
    """

    vault_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique identifier for this vault entry.",
    )
    label: str = Field(
        ...,
        description="User-defined label (e.g. 'Senior SDET Remote June 2026').",
    )
    config: SearchConfig
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
    )
    times_used: int = Field(default=0, ge=0)


# =============================================================================
# Scrape Run Session — Tracks a complete scraper execution
# =============================================================================

class ScrapeRunSummary(BaseModel):
    """
    Summary statistics for a completed scraper run.
    Displayed in the Streamlit console and stored for audit.
    """

    run_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    started_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    completed_at: Optional[datetime] = None
    total_urls_found: int = 0
    skipped_seen: int = 0       # Delta Load: already in registry
    skipped_ttl: int = 0        # Delta Load: within TTL window
    new_processed: int = 0
    tier1_count: int = 0
    tier2_count: int = 0
    tier3_count: int = 0
    domains_aborted: list[str] = Field(default_factory=list)  # Circuit breaker
    errors: list[str] = Field(default_factory=list)

    @property
    def duration_seconds(self) -> Optional[float]:
        if self.completed_at:
            return (self.completed_at - self.started_at).total_seconds()
        return None


