# Scraper Output — Raw surface metadata
# =============================================================================

class JobResult(BaseModel):
    """
    Surface metadata extracted by the scraper.
    STRICT RULE: No job description content. Title, company, salary, link only.

    Generated by: scraper.py
    Consumed by:  matcher.py, database.py
    """

    title: str = Field(..., description="Job title as displayed on the listing.")
    company: str = Field(..., description="Company name — fallback key if URL rots.")
    url: str = Field(..., description="Direct link to the job posting.")
    salary_raw: Optional[str] = Field(
        default=None,
        description="Raw salary string as scraped (e.g. '$120k - $150k'). "
                    "None if not published.",
    )
    source_domain: str = Field(..., description="The job board domain this was scraped from.")
    scraped_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of extraction.",
    )

    @field_validator("url", mode="before")
    @classmethod
    def normalize_url(cls, v: str) -> str:
        """Strip trailing slashes and whitespace for consistent hashing."""
        return str(v).strip().rstrip("/")

    @field_validator("title", "company", mode="before")
    @classmethod
    def strip_whitespace(cls, v: str) -> str:
        return str(v).strip()

    def parse_salary_usd(self) -> Optional[int]:
        """
        Parses salary_raw to an integer USD annual value.
        Returns None if no currency-anchored amount is found.

        TWO STRICTLY ANCHORED PATHS — no standalone digits accepted:

        Path 1  (dollar prefix):
            Requires a literal $ before the number.
            Matches: '$120k', '$90,000', '$120k - $150k', '$85,000/yr'
            Rejects: anything without a leading $

        Path 2  (usd suffix):
            Requires the word 'usd' immediately after the number/k.
            Matches: '120k usd', '85k USD', '90 usd'
            Rejects: '401k match' — no 'usd' follows the k, so no match

        REJECTS: '401k', '401k match', 'equity', 'DOE', 'Competitive'

        GROUP LAYOUT — 4-tuple per match (alternation produces two pairs):
            (dollar_num, dollar_k, usd_num, usd_k)
            Only ONE pair is populated per match; the other pair is empty.

        DIGIT FLOOR — the {2,3} quantifier requires at least 2 leading
        digits, preventing spurious matches on $1 or $5 text fragments.
        Minimum matchable amount: $10.

        Salary ranges ('$120k - $150k') return the minimum value —
        conservative estimate for the salary gate filter.
        """
        if not self.salary_raw:
            return None

        import re
        # Input is lowercased so the usd\b branch matches 'USD', 'usd', 'Usd'.
        # Dollar signs are not affected by lower().
        raw = self.salary_raw.lower()

        matches = re.findall(
            r'(?:\$)\s*(\d{2,3}(?:,\d{3})*(?:\.\d+)?)\s*(k)?'
            r'|'
            r'(\d{2,3}(?:\.\d+)?)\s*(k)?\s*(?:usd\b)',
            raw,
        )
        if not matches:
            return None

        values = []
        for dollar_num, dollar_k, usd_num, usd_k in matches:
            # Determine which alternation arm fired
            num_str = dollar_num if dollar_num else usd_num
            suffix  = (dollar_k  if dollar_num else usd_k).lower()
            if not num_str:
                continue
            try:
                val = float(num_str.replace(",", ""))
                if suffix == "k":
                    val *= 1000
                values.append(int(val))
            except ValueError:
                continue

        return min(values) if values else None


