# Extraction Layer — LLM Structured Job Data (The "Shy Principle" contract)
# =============================================================================

class ExtractedJob(BaseModel):
    """
    The output contract for the LLM-based job description extraction engine.

    DESIGN PHILOSOPHY — The Shy Principle:
        Every field defaults to null or an empty list.
        The LLM is forbidden from inferring or guessing. If the data is not
        explicitly stated in the source text, the field must be null.
        A null field is honest. A hallucinated field is a data integrity failure.

    FIELD DECISIONS (all changes from original prompt design documented):

        salary_min / salary_max:
            Split from a single field because job posts almost always state
            ranges ("$90k - $120k"). A single number forces arbitrary choice.
            Both are nullable integers — no string type annotations that would
            cause the LLM to return "null" (string) vs null (JSON).

        remote_region:
            Replaces the original two-boolean (is_remote_global, is_remote_us_only)
            design. Two booleans have an impossible state (both True) and no way
            to express EU-only, Canada-only, or CONFLICT cases.
            Values: "GLOBAL", "US", "EU", "CA", "CONFLICT", null

        location_conflict_detected:
            True when the metadata/title says one thing and the body text says
            another (e.g. "United States" in the dropdown but "open to candidates
            worldwide" in the description). The LLM always trusts body text over
            metadata but surfaces the conflict for human review.

        location_notes:
            Verbatim quote of the conflicting phrase from the source text.
            Never paraphrased — the LLM copies exact words. Null when no conflict.

        required_tech / preferred_tech:
            Split because job posts distinguish "Required: Python, K8s" from
            "Nice to have: Go, Terraform." Merging them means your must_include
            filter treats nice-to-haves as hard requirements.

        experience_min_years / experience_max_years:
            Replaces single years_experience. "3-5 years" is the most common
            format. A single field would silently lose half the data.

        seniority_level:
            Extracted separately from title. Saves the matcher from regex
            matching "Staff", "Senior", "Principal", "Lead" in title strings.

        employment_type:
            "full-time", "contract", "part-time", "internship", null.
            Always explicitly stated. Critical for must_exclude: ["Contract"].

        integrity_score:
            0.0 to 1.0. Uses a deterministic rubric (documented in the prompt)
            so two LLMs given the same input return the same score, not vibes.

        source_url:
            Passed in from the scraper and echoed back. Enables deduplication
            at the extraction stage without re-joining on title+company (fragile).

    Generated by: nlp_engine.extract_jobs_from_text()
    Consumed by:  matcher.py (enhanced scoring), database.py, integrations/
    """

    # ── Identity ──────────────────────────────────────────────────────────────
    title:           str             = Field(..., description="Job title exactly as written.")
    company:         str             = Field(..., description="Company name exactly as written.")
    source_url:      Optional[str]   = Field(default=None, description="URL passed in from scraper.")
    seniority_level: Optional[str]   = Field(
        default=None,
        description="Allowed values: Staff, Principal, Senior, Mid, Junior, Lead, null. Level codes like L5 or IC5 are company-specific → return null."
    )
    employment_type: Optional[str]   = Field(
        default=None,
        description="Allowed values: full-time, contract, part-time, internship, null. Contract-to-hire is contract, not full-time."
    )

    # ── Compensation ──────────────────────────────────────────────────────────
    salary_min: Optional[int]   = Field(default=None, description="Lower bound in integers. null if not stated.")
    salary_max: Optional[int]   = Field(default=None, description="Upper bound in integers. null if not stated.")
    currency:   Optional[str]   = Field(
        default=None,
        description="ISO 4217 code. Default USD when $ symbol present and no country context contradicts it."
    )

    # ── Location / Remote ─────────────────────────────────────────────────────
    remote_region: Optional[str] = Field(
        default=None,
        description=(
            "GLOBAL: explicitly says worldwide/anywhere/all countries. "
            "US: says remote but requires US residency. "
            "EU / CA: specifies that region explicitly. "
            "CONFLICT: metadata contradicts body text. "
            "null: on-site or not stated."
        )
    )
    is_hybrid: bool = Field(
        default=False,
        description="True only if the post explicitly mentions hybrid arrangement."
    )
    location_strictness: Optional[str] = Field(
        default=None,
        description=(
            "How accessible this job is for the user in Lima, Peru. "
            "Strict: requires US presence/citizenship — user cannot apply. "
            "Flexible: timezone/hours-based but contractors may qualify. "
            "Match: global, LATAM, or no restriction — user is a fit."
        )
    )
    location_notes: Optional[str] = Field(
        default=None,
        description=(
            "1-2 sentences explaining why this job works or conflicts for "
            "someone in Lima, Peru (EST/UTC-5). Quote the relevant phrase."
        )
    )

    # ── Tech Stack ────────────────────────────────────────────────────────────
    required_tech:  list[str] = Field(
        default_factory=list,
        description="Technologies explicitly marked as required. Never infer."
    )
    preferred_tech: list[str] = Field(
        default_factory=list,
        description="Technologies explicitly marked as preferred/nice-to-have. Never infer."
    )

    # ── Experience ────────────────────────────────────────────────────────────
    experience_min_years: Optional[int] = Field(
        default=None,
        description="Lower bound. '3-5 years' → 3. null if not stated."
    )
    experience_max_years: Optional[int] = Field(
        default=None,
        description="Upper bound. '3-5 years' → 5. null if not stated."
    )

    # ── Personalization ───────────────────────────────────────────────────────
    cv_match_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description=(
            "How well the job's tech stack matches the user's core skills. "
            "1.0 = perfect overlap. 0.0 = zero overlap. Always computed."
        )
    )

    # ── Quality Signal ────────────────────────────────────────────────────────
    integrity_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description=(
            "Additive score 0.0-1.0. Add +0.2 for each: salary stated as number, "
            "tech stack has 1+ items, experience stated, location unambiguous (Case A-D), "
            "company+title both present."
        )
    )

    @field_validator("title", "company", mode="before")
    @classmethod
    def strip_and_require_nonempty(cls, v):
        """Strips whitespace and rejects empty or whitespace-only strings."""
        if v is None:
            raise ValueError("field is required and cannot be null")
        cleaned = str(v).strip()
        if not cleaned:
            raise ValueError("field cannot be empty or whitespace-only")
        return cleaned

    @field_validator("salary_min", "salary_max", mode="before")
    @classmethod
    def coerce_salary(cls, v):
        """Coerces string salary values to int, rejects non-numeric."""
        if v is None:
            return None
        if isinstance(v, (int, float)):
            return int(v)
        if isinstance(v, str):
            cleaned = v.strip().replace(",", "").replace("$", "").replace("k", "000").lower()
            try:
                return int(float(cleaned))
            except ValueError:
                return None
        return None

    @field_validator("location_strictness", mode="before")
    @classmethod
    def normalize_location_strictness(cls, v):
        if v is None:
            return None
        allowed = {"Strict", "Flexible", "Match"}
        for a in allowed:
            if str(v).strip().lower() == a.lower():
                return a
        return None

    @field_validator("cv_match_score", mode="before")
    @classmethod
    def clamp_cv_match(cls, v):
        try:
            return max(0.0, min(1.0, float(v)))
        except (TypeError, ValueError):
            return 0.0

    @field_validator("remote_region", mode="before")
    @classmethod
    def normalize_remote_region(cls, v):
        """Normalises to uppercase allowed values."""
        if v is None:
            return None
        allowed = {"GLOBAL", "US", "EU", "CA", "CONFLICT"}
        upper = str(v).strip().upper()
        return upper if upper in allowed else None

    @field_validator("employment_type", mode="before")
    @classmethod
    def normalize_employment_type(cls, v):
        """Normalises to lowercase allowed values."""
        if v is None:
            return None
        allowed = {"full-time", "contract", "part-time", "internship"}
        lower = str(v).strip().lower()
        return lower if lower in allowed else None

    @field_validator("integrity_score", mode="before")
    @classmethod
    def clamp_integrity(cls, v):
        """Clamps to [0.0, 1.0] in case LLM returns out-of-range value."""
        try:
            return max(0.0, min(1.0, float(v)))
        except (TypeError, ValueError):
            return 0.0


class ExtractionResult(BaseModel):
    """
    Wrapper for the full output of extract_jobs_from_text().
    A list of ExtractedJob objects. Empty list signals garbage/duplicate input.

    Generated by: nlp_engine.extract_jobs_from_text()
    """
    jobs: list[ExtractedJob] = Field(default_factory=list)

    @model_validator(mode="before")
    @classmethod
    def skip_invalid_jobs(cls, data):
        """
        Validates each job entry individually and silently drops any that fail
        (missing/empty title or company). Valid entries are never affected.
        """
        if not isinstance(data, dict) or "jobs" not in data:
            return data
        valid = []
        for raw in data.get("jobs") or []:
            try:
                ExtractedJob.model_validate(raw)
                valid.append(raw)
            except Exception:
                pass
        data["jobs"] = valid
        return data
