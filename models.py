# Intelligence Layer — Scored and bucketed job
# =============================================================================

class TieredJob(BaseModel):
    """
    A JobResult enriched with a match score and tier classification.

    Generated by: matcher.py
    Consumed by:  main.py (display), integrations/
    """

    job: JobResult
    match_score: int = Field(
        ...,
        ge=-1,
        le=100,
        description=(
            "0–100 match percentage for scored tiers (Tier 1/2/3). "
            "-1 is the sentinel value for Tier 4 (Manual Review) jobs "
            "that bypass mathematical scoring entirely."
        ),
    )
    tier: str = Field(..., description="'Tier 1', 'Tier 2', or 'Tier 3'.")
    match_reasons: list[str] = Field(
        default_factory=list,
        description="Human-readable list of which criteria matched.",
    )
    miss_reasons: list[str] = Field(
        default_factory=list,
        description="Human-readable list of which criteria did NOT match.",
    )

    @field_validator("tier")
    @classmethod
    def validate_tier(cls, v: str) -> str:
        allowed = {"Tier 1", "Tier 2", "Tier 3", "Tier 4"}
        if v not in allowed:
            raise ValueError(f"tier must be one of {allowed}, got '{v}'")
        return v


