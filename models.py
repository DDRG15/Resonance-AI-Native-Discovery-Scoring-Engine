"""
models.py — Pydantic v2 Data Contracts for Project GEMA.

Every layer of the pipeline communicates through these models.
No raw dicts cross module boundaries — every piece of data is validated
at the entry point and typed throughout its lifetime.

Architecture role:
    NLP Engine  → produces SearchConfig
    Scraper     → produces list[JobResult]
    Matcher     → produces list[TieredJob]
    Database    → persists/retrieves SearchVaultEntry
    Integrations→ consume TieredJob to push to Notion/Sheets
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Optional
from pydantic import BaseModel, Field, field_validator, model_validator


# =============================================================================
# NLP Contract — Output of the LLM Engine
# =============================================================================

class SearchConfig(BaseModel):
    """
    The structured output of the NLP engine.
    This is the 'source of truth' contract that all downstream layers consume.

    Generated by: nlp_engine.py
    Consumed by:  scraper.py, matcher.py, database.py (vault)
    """

    target_titles: list[str] = Field(
        ...,
        min_length=1,
        description="Job titles to search for. At least one required.",
        examples=[["Senior SDET", "Automation Engineer", "QA Automation"]],
    )
    must_include: list[str] = Field(
        default_factory=list,
        description="Keywords that MUST appear in title or salary metadata.",
        examples=[["Remote", "100% Remote"]],
    )
    must_exclude: list[str] = Field(
        default_factory=list,
        description="Keywords that disqualify a job if found.",
        examples=[["Contract", "Hybrid", "On-site"]],
    )
    min_salary: Optional[int] = Field(
        default=None,
        ge=0,
        description="Minimum annual salary in USD. None = no filter.",
        examples=[90000],
    )
    target_domains: list[str] = Field(
        default_factory=list,
        description="Job board domains to scrape.",
        examples=[["himalayas.app", "trueup.io"]],
    )

    # God Mode overrides (Vol 1.1 / Vol 1.4)
    custom_xpath: Optional[str] = Field(
        default=None,
        description="God Mode: custom XPath selector for job card title element.",
    )
    custom_css: Optional[str] = Field(
        default=None,
        description="God Mode: custom CSS selector override for job card.",
    )

    @field_validator("target_titles", "must_include", "must_exclude", mode="before")
    @classmethod
    def strip_and_deduplicate(cls, v: list) -> list:
        """Normalize whitespace and remove duplicates while preserving order."""
        seen: set = set()
        result: list = []
        for item in v:
            cleaned = str(item).strip()
            if cleaned and cleaned.lower() not in seen:
                seen.add(cleaned.lower())
                result.append(cleaned)
        return result

    @field_validator("target_domains", mode="before")
    @classmethod
    def normalize_domains(cls, v: list) -> list:
        """Strip protocols and trailing slashes from domain strings."""
        cleaned = []
        for domain in v:
            d = str(domain).strip()
            d = d.replace("https://", "").replace("http://", "").rstrip("/")
            if d:
                cleaned.append(d)
        return cleaned

    @model_validator(mode="after")
    def validate_no_overlap(self) -> SearchConfig:
        """Must-include and must-exclude cannot share keywords."""
        include_lower = {k.lower() for k in self.must_include}
        exclude_lower = {k.lower() for k in self.must_exclude}
        overlap = include_lower & exclude_lower
        if overlap:
            raise ValueError(
                f"Keywords cannot be in both must_include and must_exclude: {overlap}"
            )
        return self


